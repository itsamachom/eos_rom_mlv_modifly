"""Shape Thai offline with RAQM/HarfBuzz; emit bounded 1-bit phrase masks.

The camera never parses UTF-8 or extracts fonts from Canon firmware. Unknown
strings retain their original English text. Regeneration requires Pillow/RAQM.
"""
from pathlib import Path
import hashlib
import json
import math
import struct
import zlib
from PIL import Image, ImageDraw, ImageFont, features
from fontTools.ttLib import TTFont

root = Path(__file__).resolve().parents[1]
assert features.check_feature("raqm"), "RAQM/HarfBuzz shaping is required"
font_path = root / "assets/fonts/noto-sans-thai/NotoSansThai.ttf"
lexicon = json.loads((root / "translations/photo_th.json").read_text())
font_data = TTFont(font_path)
cmap = font_data.getBestCmap()
sizes = (23, 28, 32)
fonts = {}
for size in sizes:
    font = ImageFont.truetype(str(font_path), size, layout_engine=ImageFont.Layout.RAQM)
    font.set_variation_by_axes([600, 100])
    fonts[size] = font
data = bytearray()
records = []
dedup = {}
oversize = []


def zero_packbits(raw):
    encoded = bytearray()
    i = 0
    while i < len(raw):
        if raw[i] == 0 and i + 1 < len(raw) and raw[i + 1] == 0:
            end = i
            while end < len(raw) and raw[end] == 0 and end - i < 128:
                end += 1
            encoded.append(128 + end - i - 1)
        else:
            end = i + 1
            while end < len(raw) and end - i < 128 and not (raw[end] == 0 and end + 1 < len(raw) and raw[end + 1] == 0):
                end += 1
            encoded.append(end - i - 1)
            encoded.extend(raw[i:end])
        i = end
    return encoded


for key, entry in lexicon.items():
    text = entry["th"]
    assert all(ord(c) in cmap for c in text), (key, text)
    if text == key:
        continue
    variants = []
    for size in sizes:
        cache_key = (text, size)
        if cache_key not in dedup:
            font = fonts[size]
            bbox = font.getbbox(text, language="th", direction="ltr")
            left_pad = max(0, -bbox[0])
            width = math.ceil(max(font.getlength(text, language="th"), bbox[2])) + left_pad + 1
            height = max(math.ceil(size * 1.35), bbox[3] + 1)
            if width > entry["max_width"]:
                oversize.append((key, text, size, width, entry["max_width"]))
            image = Image.new("L", (width, height))
            ImageDraw.Draw(image).text((left_pad, 0), text, font=font, fill=255, language="th", direction="ltr")
            stride = (width + 7) // 8
            packed = bytearray(stride * height)
            for y in range(height):
                for x in range(width):
                    if image.getpixel((x, y)) >= 100:
                        packed[y * stride + x // 8] |= 0x80 >> (x % 8)
            encoded = zero_packbits(packed)
            dedup[cache_key] = (len(data), width, height, len(encoded))
            data.extend(encoded)
        variants.append(dedup[cache_key])
    records.append((key, variants))
if oversize:
    raise SystemExit("Shorten translations to avoid clipping:\n" + "\n".join(map(str, oversize)))
assert len(data) <= 512 * 1024, "Thai atlas exceeds the bounded camera allocation"
asset_dir = root / "firmware/data/photo_thai"
asset_dir.mkdir(parents=True, exist_ok=True)
(asset_dir / "PHOTO_TH.BIN").write_bytes(data)
header = ["/* Generated by tools/generate_photo_thai.py; do not edit. */",
          f"#define PHOTO_TH_BYTES {len(data)}u", f"#define PHOTO_TH_CRC 0x{zlib.crc32(data):08x}u",
          "struct photo_thai_mask { unsigned offset; unsigned short width, height, encoded_size; };",
          "struct photo_thai_phrase { const char * key; struct photo_thai_mask masks[3]; };",
          "static const struct photo_thai_phrase photo_thai_phrases[] = {"]
assert len({key.split('\n')[0][:99].rstrip() for key, _ in records}) == len(records), "Ambiguous English lookup keys"
for key, variants in records:
    header.append("    {" + json.dumps(key.split('\n')[0][:99].rstrip()) + ", {" + ", ".join("{%du, %d, %d, %d}" % b for b in variants) + "}},")
header.append("};\n")
(root / "firmware/src/photo-thai-data.h").write_text("\n".join(header))
(asset_dir / "manifest.json").write_text(json.dumps({
    "font": "Noto Sans Thai", "weight": 600, "font_version": font_data['name'].getDebugName(5),
    "font_sha256": hashlib.sha256(font_path.read_bytes()).hexdigest(),
    "atlas_sha256": hashlib.sha256(data).hexdigest(), "atlas_crc32": "%08x" % zlib.crc32(data),
    "atlas_bytes": len(data), "translated_phrases": len(records), "font_sizes": sizes,
    "shaping": "Pillow RAQM/HarfBuzz, language th, ltr", "pillow": Image.__version__,
}, indent=2) + "\n")
print("Generated", len(records), "phrases; atlas", len(data), "bytes; CRC32 %08x" % zlib.crc32(data))

# Standalone proof of font shaping, explicitly not a camera screenshot.
proof = Image.new("RGB", (1050, 760), "#101820")
draw = ImageDraw.Draw(proof)
samples = ["ถ่ายภาพ", "ตั้งค่า", "ไฮไลต์จุดชัด", "ถ่ายคร่อมโฟกัส", "ความเร็วชัตเตอร์", "สมดุลแสงขาว",
           "กิ กี้ กุ กู้ น้ำ ตั้งค่า", "ซ้าย/ขวา ปรับค่า   SET เสร็จ"]
draw.text((25, 10), "Thai font shaping proof — not a camera screenshot", font=fonts[28], fill="#ffb13b")
for i, text in enumerate(samples):
    draw.text((30, 75 + i * 78), text, font=fonts[32], fill="#f1f5f9", language="th")
    draw.text((570, 75 + i * 78), text, font=fonts[28], fill="#66d9ef", language="th")
preview = root / "previews"
preview.mkdir(exist_ok=True)
proof.save(preview / "thai-font-proof.png")
