"""Bake cylinder/softbox profiles, inspired by M-Film's column-based renderer.
No runtime floating point, palette changes or external image textures.
"""
from pathlib import Path
import math
root=Path(__file__).resolve().parents[1]
rows=[]
for x in range(92):
 n=(x+.5)/46-1;t=math.asin(n);z=math.sqrt(1-n*n)
 u=round((t/math.pi+.5)*143)
 light=max(.20,min(1.0,.24+.76*max(0,math.cos(t+.42))))
 spec=.34*math.exp(-((t+.39)/.16)**2)+.15*math.exp(-((t-1.22)/.12)**2)
 metal=.17+.30*max(0,math.cos(t+.35))+.42*math.exp(-((t+.38)/.16)**2)+.20*math.exp(-((t-1.25)/.17)**2)
 rows.append((u,round(-2+8*z),round(light*255),round(spec*255),round(min(1,metal)*100)))
h='''/* Cylinder profile: independent fork implementation inspired by M-Film's
 * texture-column / diffuse / specular shading approach (fos_film.c, 8118e9c).
 * GPL-2.0-or-later. Generated by tools/generate_film_cylinder.py. */
struct photo_film_column { unsigned char u; signed char dy; unsigned char light,spec,metal; };
static const struct photo_film_column photo_film_columns[92]={\n'''
h+=''.join('    {'+','.join(map(str,r))+'},\n' for r in rows)+'};\n'
h+='static const unsigned char photo_film_cap_height[98]={'+','.join(str(round(7*math.sqrt(1-((i+.5)/49-1)**2))) for i in range(98))+'};\n'
(root/'firmware/src/photo-film-cylinder-600d.h').write_text(h)
print('Generated cylinder angle, curvature, diffuse/specular and steel profiles')
