"""Audit original native JPEG recipes from a checkout of the pinned M-Film commit.
Usage: python tools/import_original_jpeg_tones.py /path/to/upstream-checkout
Does not execute upstream Python or import LUT/RAW development code.
"""
from pathlib import Path
import ast,re,json,hashlib
import sys,subprocess
root=Path(__file__).resolve().parents[1]; upstream=Path(sys.argv[1])
files=['ml-dev/filmos/fos_film.c','ml-dev/filmos/tools/genfilms.py','ml-dev/films/films.py','ml-dev/films/filmluts.py','ml-dev/fork/src/filmroll.c']
assert subprocess.check_output(['git','rev-parse','HEAD'],cwd=upstream,text=True).strip()=='8118e9c7c072371bd53eda8920f44910e8a35baf', 'Use the audited upstream commit'
source={p:(upstream/p).read_text() for p in files}
constants={'PS_STANDARD':0x81,'PS_LANDSCAPE':0x83,'PS_MONO':0x86}
groups={'FOS_GROUP_COLOUR':0,'FOS_GROUP_SLIDE':1,'FOS_GROUP_CINE':2,'FOS_GROUP_BW':3}
rows=[]
block=source[files[0]].split('static const struct fos_film builtin[] =',1)[1].split('};',1)[0]
for entry in re.findall(r'\{([^{}]+)\}',block):
 fields=[f.strip() for f in entry.split(',')]
 # Description contains commas: use tokenization instead.
 fields=re.findall(r'"(?:[^"\\]|\\.)*"|[A-Za-z_][A-Za-z_0-9]*|-?\d+',entry)
 key,brand,name,process,desc=[ast.literal_eval(s) for s in fields[:5]]
 vals=[constants[v] if v in constants else int(v) for v in fields[5:15]]
 box,iso,style,c,sat,tone,sharp,k,gm,ba=vals
 rows.append(dict(key=key,brand=brand,name=name,process=process,group=groups[fields[-2]],box_iso=box,camera_iso=iso,style=style,contrast=c,sharpness=sharp,saturation=sat,color_tone=tone,kelvin=k,gm=gm,ba=ba,origin='builtin'))
tree=ast.parse(source[files[3]])
stocks=next(ast.literal_eval(n.value) for n in tree.body if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='STOCKS' for t in n.targets))
gen=ast.parse(source[files[1]])
style_node=next(n.value.value for n in ast.walk(gen) if isinstance(n,ast.Assign) and any(isinstance(t,ast.Name) and t.id=='style' for t in n.targets))
class Replace(ast.NodeTransformer):
 def visit_Name(self,node):return ast.copy_location(ast.Constant(constants[node.id]),node) if node.id in constants else node
styles=ast.literal_eval(Replace().visit(style_node))
for key,_,brand,name,box,kind in [('cinestill400t','','CineStill','400T',400,'cine')]+stocks:
 style,c,sat,tone=styles[kind]
 process={'neg':'C-41','slide':'E-6','xpro':'X-PRO','bw':'B&W','cine':'C-41','print':'ECP'}[kind]
 if key.startswith('kodachrome'):process='K-14'
 if key in ('xp2','bw400cn'):process='C-41'
 rows.append(dict(key=key,brand=brand.upper(),name=name,process=process,group={'neg':0,'slide':1,'xpro':1,'cine':2,'print':2,'bw':3}[kind],box_iso=box,camera_iso=max(100,box),style=style,contrast=c,sharpness=2,saturation=sat,color_tone=tone,kelvin=5200,gm=0,ba=0,origin='genfilms.py'))
for r in rows:
 raw=72;i=100
 while i<r['camera_iso']:raw+=8;i*=2
 r['raw_iso']=raw;r['effective_iso']=i
assert len(rows)==72 and len({r['key'] for r in rows})==72
catalog=dict(upstream='https://github.com/HNGSeries/mfilm-canon-film-simulation',commit='8118e9c7c072371bd53eda8920f44910e8a35baf',license='GPL-2.0-only',scope='Original native JPEG preview settings, not developed RAW/LUT looks',iso_conversion='Preserves filmroll.c iso_to_raw: round up to a whole stop from ISO100; ISO125/160 become ISO200',source_sha256={p:hashlib.sha256(source[p].encode()).hexdigest() for p in files},recipes=rows)
(root/'research/jpeg-tones/UPSTREAM_ORIGINAL_CATALOG.json').write_text(json.dumps(catalog,indent=2)+'\n')
print('Imported',len(rows),'original profiles')

header = """/* Native JPEG preview recipes derived from HNGSeries/M-Film 0.2.1, commit
 * 8118e9c7c072371bd53eda8920f44910e8a35baf. Copyright M-Film contributors.
 * GPL-2.0-only. Original numbers and ISO conversion retained; independent UI.
 * Generated by tools/import_original_jpeg_tones.py; see research/jpeg-tones.
 * Not the developed RAW/LUT looks. Names identify presets, not endorsements. */
#ifndef PHOTO_TONE_RECIPES_600D_H
#define PHOTO_TONE_RECIPES_600D_H
struct photo_tone_recipe {
    const char *name, *brand, *key, *process;
    int group, style, contrast, sharpness, saturation, color_tone, kelvin, gm, ba;
    int box_iso, camera_iso, raw_iso, effective_iso;
};
static const char *const photo_tone_groups[] = {"Color Tones","Slide Tones","Cinema Tones","Mono Tones"};
static const struct photo_tone_recipe photo_tone_recipes[] = {
"""
for r in rows:
 fields=[json.dumps(r[k]) for k in ('name','brand','key','process')]+[str(r[k]) for k in ('group','style','contrast','sharpness','saturation','color_tone','kelvin','gm','ba','box_iso','camera_iso','raw_iso','effective_iso')]
 header+='    {'+','.join(fields)+'},\n'
header+="};\n#define PHOTO_TONE_COUNT ((int)(sizeof(photo_tone_recipes)/sizeof(photo_tone_recipes[0])))\n#endif\n"
(root/'firmware/src/photo-tone-recipes-600d.h').write_text(header)
